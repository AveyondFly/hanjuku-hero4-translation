def _norm(jp: str) -> str:
    return (jp or "").replace(" ", "")


def decode_trump_name(raw: bytes) -> str:
    toks = decode_font_codes(raw, mul48=False)
    return _norm(codes_to_text(toks))


def translate_trump(jp: str) -> str:
    jp = _norm(jp)
    if not jp:
        return ""
    hit = HAND.get(jp)
    if hit:
        return hit
    if jp.endswith("のおまもり") and len(jp) > 6:
        head = jp[: -len("のおまもり")]
        if _is_kana_name(head):
            return _kana_to_zh(head) + "护身符"
        return head + "护身符"
    if jp.endswith("のカギ") and len(jp) > 3:
        head = jp[: -len("のカギ")]
        if _is_kana_name(head):
            return _kana_to_zh(head) + "钥匙"
        return head + "钥匙"
    if _is_kana_name(jp):
        return _kana_to_zh(jp)
    return ""
