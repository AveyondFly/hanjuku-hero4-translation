def fill_generated() -> dict[str, str]:
    out: dict[str, str] = {}
    # Name-entry Latin overlay (sysmes_alphabet). Indices 66+ are punctuation:
    # those are filled from jp in apply_zh via leftover copy below.
    row = [""] * 119
    for i, ch in enumerate("ABCDEFGHIJKLM"):
        row[i] = ch
    row[14], row[15], row[16] = "1", "2", "3"
    for i, ch in enumerate("NOPQRSTUVWXYZ"):
        row[17 + i] = ch
    row[31], row[32], row[33] = "4", "5", "6"
    for i, ch in enumerate("abcdefghijklm"):
        row[34 + i] = ch
    row[48], row[49], row[50] = "7", "8", "9"
    for i, ch in enumerate("nopqrstuvwxyz"):
        row[51 + i] = ch
    row[65] = "0"
    for i, ch in enumerate(row):
        if ch:
            out[f"sysmes_alphabet#{i}"] = ch
    return out


