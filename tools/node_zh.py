def _latin_plate(head: str) -> str | None:
    out: list[str] = []
    for ch in head:
        if ch == "ー":
            out.append("-")
            continue
        if ch.isdigit():
            out.append(ch)
            continue
        mapped = _PLATE_CH.get(ch)
        if mapped is None:
            return None
        out.append(mapped)
    s = "".join(out)
    if not s or not any(c.isalpha() for c in s):
        return None
    return s


def _pattern_zh(jp: str) -> str | None:
    if jp.endswith("敗新"):
        head = jp[: -len("敗新")]
        if head.isdigit():
            return f"{head}基地"
    for src, dst in (
        ("土地", "地"),
        ("戦場", "战场"),
        ("地形", "地形"),
        ("风景", "风景"),
        ("揺見", "风景"),
        ("置地", "基地"),
        ("プレート", "台"),
        ("サンゴ", "珊瑚"),
        ("システム", "系统"),
        ("ムクロ", "尸"),
    ):
        if jp.endswith(src) and len(jp) > len(src):
            head = jp[: -len(src)]
            if src == "プレート" and head.endswith("番"):
                num = head[:-1]
                if num.isdigit():
                    return f"{num}号台"
            if src == "プレート" and head.isdigit():
                return f"{head}台"
            if src == "プレート":
                latin = _latin_plate(head)
                if latin:
                    return latin + dst
            if _is_kana_name(head):
                return _kana_to_zh(head) + dst
            if src == "土地" and jp.endswith("土地"):
                if "{" in head:
                    return None
            return None
    return None


def translate_node(jp: str) -> str:
    jp = (jp or "").strip()
    if not jp or "{" in jp:
        return ""
    if jp in HAND:
        return HAND[jp]
    pat = _pattern_zh(jp)
    if pat:
        return pat
    if _is_kana_name(jp):
        return _kana_to_zh(jp)
    return ""
