def by_id() -> dict[str, str]:
    return dict(NAMES)


def speaker(eid: str) -> str:
    """Chinese display name for an egg id prefix like eg_pw_bari."""
    if eid in NAMES:
        return NAMES[eid]
    parts = eid.split("_")
    if len(parts) >= 3:
        base = "_".join(parts[:3])
        if base in NAMES:
            return NAMES[base]
    return ""
