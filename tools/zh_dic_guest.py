def by_id() -> dict[str, str]:
    out: dict[str, str] = {}
    with CSV.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            sid = row["id"]
            if not sid.startswith("menu_dic"):
                continue
            jp = row.get("jp") or ""
            if jp in JP2ZH:
                out[sid] = JP2ZH[jp]
    return out
