def _glyph_char(code) -> str:
    if isinstance(code, int) and code in NODE_GLYPH:
        return NODE_GLYPH[code]
    return glyph_to_char(code)


def decode_node_title(raw: bytes) -> str:
    toks = decode_font_codes(raw, mul48=False)
    if toks and toks[-1] == 195:
        toks = toks[:-1]
    suffix = ""
    # Alma/romance titles use other 2-byte slots than mes for 地形/风景.
    if len(toks) >= 2 and all(isinstance(t, int) and t < 192 for t in toks[:-2]):
        if toks[-2:] == [225, 221]:
            toks = toks[:-2]
            suffix = "地形"
        elif toks[-2:] == [233, 240]:
            toks = toks[:-2]
            suffix = "风景"
    chars = [(_glyph_char(t) if isinstance(t, int) else "") for t in toks]
    s = "".join(chars)
    out: list[str] = []
    for i, ch in enumerate(s):
        if ch == "っ" and i > 0 and "\u30a0" <= s[i - 1] <= "\u30ff":
            out.append("ッ")
        else:
            out.append(ch)
    return "".join(out).replace("っ", "ッ") + suffix


def _is_kana_name(s: str) -> bool:
    if not s:
        return False
    for ch in s:
        o = ord(ch)
        if ch in "ーッっ・？!！" or 0x30A0 <= o <= 0x30FF or 0x3040 <= o <= 0x309F:
            continue
        return False
    return True


def _kana_to_zh(s: str) -> str:
    s = s.replace("っ", "").replace("ッ", "").replace("・", "·")
    out: list[str] = []
    i = 0
    while i < len(s):
        if s[i] == "ー":
            i += 1
            continue
        if s[i] in "？?!！·":
            out.append(s[i] if s[i] != "!" else "！")
            i += 1
            continue
        tri = s[i : i + 2]
        if tri in _MORA:
            out.append(_MORA[tri])
            i += 2
            continue
        one = s[i]
        out.append(_MORA.get(one, one))
        i += 1
    return "".join(out)


